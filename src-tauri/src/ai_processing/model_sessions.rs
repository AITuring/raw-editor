//! Lazily initialised ONNX sessions held in AiState.
//!
//! Each getter downloads and verifies its models on first use under the shared
//! initialisation lock and keeps the sessions for later calls.

use anyhow::Result;
use ort::session::Session;
use std::sync::Arc;
use std::sync::Mutex;
use tauri::Emitter;
use tokenizers::Tokenizer;
use tokio::sync::Mutex as TokioMutex;

use super::{
    AiModels, AiState, CLIP_MODEL_FILENAME, CLIP_MODEL_SHA256, CLIP_MODEL_URL,
    CLIP_TOKENIZER_FILENAME, CLIP_TOKENIZER_URL, ClipModels, DECODER_FILENAME, DECODER_SHA256,
    DECODER_URL, DENOISE_FILENAME, DENOISE_SHA256, DENOISE_URL, DEPTH_FILENAME, DEPTH_SHA256,
    DEPTH_URL, ENCODER_FILENAME, ENCODER_SHA256, ENCODER_URL, LAMA_FILENAME, LAMA_SHA256, LAMA_URL,
    SKYSEG_FILENAME, SKYSEG_SHA256, SKYSEG_URL, U2NETP_FILENAME, U2NETP_SHA256, U2NETP_URL,
    download_and_verify_model, download_model, ensure_onnx_runtime, get_models_dir,
};

pub async fn get_or_init_ai_models(
    app_handle: &tauri::AppHandle,
    ai_state_mutex: &Mutex<Option<AiState>>,
    ai_init_lock: &TokioMutex<()>,
) -> Result<Arc<AiModels>> {
    if let Some(models) = ai_state_mutex
        .lock()
        .unwrap()
        .as_ref()
        .and_then(|state| state.models.clone())
    {
        return Ok(models);
    }

    let _guard = ai_init_lock.lock().await;

    if let Some(models) = ai_state_mutex
        .lock()
        .unwrap()
        .as_ref()
        .and_then(|state| state.models.clone())
    {
        return Ok(models);
    }

    let models_dir = get_models_dir(app_handle)?;
    ensure_onnx_runtime(app_handle, &models_dir).await?;

    download_and_verify_model(
        app_handle,
        &models_dir,
        ENCODER_FILENAME,
        ENCODER_URL,
        ENCODER_SHA256,
        "SAM Encoder",
    )
    .await?;
    download_and_verify_model(
        app_handle,
        &models_dir,
        DECODER_FILENAME,
        DECODER_URL,
        DECODER_SHA256,
        "SAM Decoder",
    )
    .await?;
    download_and_verify_model(
        app_handle,
        &models_dir,
        U2NETP_FILENAME,
        U2NETP_URL,
        U2NETP_SHA256,
        "Foreground Model",
    )
    .await?;
    download_and_verify_model(
        app_handle,
        &models_dir,
        SKYSEG_FILENAME,
        SKYSEG_URL,
        SKYSEG_SHA256,
        "Sky Model",
    )
    .await?;
    download_and_verify_model(
        app_handle,
        &models_dir,
        DEPTH_FILENAME,
        DEPTH_URL,
        DEPTH_SHA256,
        "Depth Model",
    )
    .await?;

    let _ = ort::init().with_name("AI").commit();

    let encoder_path = models_dir.join(ENCODER_FILENAME);
    let decoder_path = models_dir.join(DECODER_FILENAME);
    let u2netp_path = models_dir.join(U2NETP_FILENAME);
    let sky_seg_path = models_dir.join(SKYSEG_FILENAME);
    let depth_path = models_dir.join(DEPTH_FILENAME);

    let sam_encoder = Session::builder()?.commit_from_file(encoder_path)?;
    let sam_decoder = Session::builder()?.commit_from_file(decoder_path)?;
    let u2netp = Session::builder()?.commit_from_file(u2netp_path)?;
    let sky_seg = Session::builder()?.commit_from_file(sky_seg_path)?;
    let depth_anything = Session::builder()?.commit_from_file(depth_path)?;

    crate::register_exit_handler();

    let models = Arc::new(AiModels {
        sam_encoder: Mutex::new(sam_encoder),
        sam_decoder: Mutex::new(sam_decoder),
        u2netp: Mutex::new(u2netp),
        sky_seg: Mutex::new(sky_seg),
        depth_anything: Mutex::new(depth_anything),
    });

    let mut ai_state_lock = ai_state_mutex.lock().unwrap();
    if let Some(state) = ai_state_lock.as_mut() {
        state.models = Some(models.clone());
    } else {
        *ai_state_lock = Some(AiState {
            models: Some(models.clone()),
            denoise_model: None,
            clip_models: None,
            lama_model: None,
            embeddings: None,
            depth_map: None,
        });
    }

    Ok(models)
}

